<#
.SYNOPSIS
  Runs the OpenDialer server automatically on Windows using Task Scheduler (no extra software).

.DESCRIPTION
  Creates a scheduled task (default name "OpenDialer") that starts the OpenDialer server
  at system startup (as SYSTEM, before anyone logs on) or at your logon, restarts it if it
  crashes and never stops it after a time limit.

  Environment variables cannot be attached to a scheduled task directly, so the script writes
  a small launcher, <DataDir>\opendialer-service.cmd, that sets DATA_DIR/PORT/HTTPS_PORT/...
  and starts Node.js. Server output goes to <DataDir>\logs\server.log.

  Prerequisites: Node.js 20+ installed, and the repository built (`npm install` + `npm run build`).
  Run from an elevated PowerShell ("Run as administrator").

  Alternative: NSSM (https://nssm.cc) - see docs/DEPLOYMENT.md.

.PARAMETER InstallDir
  Repository root (folder containing package.json and packages\server). Default: two levels above this script.

.PARAMETER DataDir
  Data directory (database, recordings, TLS certificate, backups).
  Default: <InstallDir>\packages\server\data - the same folder `npm start` uses.

.PARAMETER Trigger
  Startup (default; runs as SYSTEM, no logon needed) or Logon (runs as the current user when they log on).

.PARAMETER OpenFirewall
  Also add inbound Windows Firewall rules for the HTTP and HTTPS ports (Private + Domain networks).

.PARAMETER DryRun
  Show what would be done without changing anything (no administrator rights needed).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\scripts\windows\install-service.ps1 -OpenFirewall

.EXAMPLE
  .\scripts\windows\install-service.ps1 -DataDir D:\OpenDialerData -Port 80 -HttpsPort 443 -DryRun
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
  [string]$InstallDir,
  [string]$DataDir,
  [string]$TaskName = 'OpenDialer',
  [ValidateSet('Startup', 'Logon')]
  [string]$Trigger = 'Startup',
  [int]$Port = 8080,
  [int]$HttpsPort = 8443,
  [string]$Tls = 'auto',
  [string]$NodePath,
  [string]$LogLevel = 'info',
  [switch]$OpenFirewall,
  [switch]$NoStart,
  [switch]$DryRun
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Write-Step([string]$msg) { Write-Host "==> $msg" -ForegroundColor Cyan }
function Write-Plan([string]$msg) { Write-Host "    [dry-run] $msg" -ForegroundColor Yellow }

$apply = -not $DryRun -and -not $WhatIfPreference

# ---------- resolve paths ----------
if (-not $InstallDir) {
  $scriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
  $InstallDir = (Resolve-Path (Join-Path $scriptDir '..\..')).Path
}
if (-not $DataDir) { $DataDir = Join-Path $InstallDir 'packages\server\data' }
$entry = Join-Path $InstallDir 'packages\server\dist\index.js'
if (-not $NodePath) {
  $cmd = Get-Command node -ErrorAction SilentlyContinue
  if ($cmd) { $NodePath = $cmd.Source }
}

Write-Step 'OpenDialer service installer (Task Scheduler)'
Write-Host "    Install dir : $InstallDir"
Write-Host "    Data dir    : $DataDir"
Write-Host "    Node.js     : $(if ($NodePath) { $NodePath } else { '(not found)' })"
Write-Host "    Task        : $TaskName  (trigger: $Trigger)"
Write-Host "    Ports       : http $Port, https $HttpsPort (TLS=$Tls)"

$problems = @()
if (-not $NodePath -or -not (Test-Path $NodePath)) { $problems += 'Node.js was not found. Install Node.js 20+ from https://nodejs.org or pass -NodePath.' }
if (-not (Test-Path (Join-Path $InstallDir 'package.json'))) { $problems += "No package.json in $InstallDir. Pass -InstallDir <repository folder>." }
if (-not (Test-Path $entry)) { $problems += "Server is not built ($entry missing). Run: npm install; npm run build" }

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) { $problems += 'Not running as administrator. Right-click PowerShell -> "Run as administrator".' }

if ($problems.Count) {
  foreach ($p in $problems) { Write-Warning $p }
  if ($apply) { throw 'Cannot continue - fix the problems above (or use -DryRun to preview).' }
}

# ---------- launcher ----------
$launcher = Join-Path $DataDir 'opendialer-service.cmd'
$logDir = Join-Path $DataDir 'logs'
$launcherBody = @"
@echo off
rem Generated by scripts\windows\install-service.ps1 - re-run the installer to change settings.
set "DATA_DIR=$DataDir"
set "PORT=$Port"
set "HTTPS_PORT=$HttpsPort"
set "TLS=$Tls"
set "LOG_LEVEL=$LogLevel"
set "NODE_ENV=production"
cd /d "$InstallDir"
if not exist "$logDir" mkdir "$logDir"
"$NodePath" "$entry" >> "$logDir\server.log" 2>&1
"@

Write-Step "Write launcher $launcher"
if ($apply) {
  New-Item -ItemType Directory -Force -Path $DataDir, $logDir | Out-Null
  Set-Content -Path $launcher -Value $launcherBody -Encoding ASCII
} else {
  Write-Plan "would create $DataDir and $logDir"
  Write-Plan "would write launcher:`n$launcherBody"
}

# ---------- scheduled task ----------
$action = New-ScheduledTaskAction -Execute 'cmd.exe' -Argument "/c `"$launcher`"" -WorkingDirectory $InstallDir
$settings = New-ScheduledTaskSettingsSet `
  -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) `
  -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew

if ($Trigger -eq 'Startup') {
  $taskTrigger = New-ScheduledTaskTrigger -AtStartup
  $principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
  $who = 'SYSTEM at startup'
} else {
  $user = "$env:USERDOMAIN\$env:USERNAME"
  $taskTrigger = New-ScheduledTaskTrigger -AtLogOn -User $user
  $principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
  $who = "$user at logon"
}

Write-Step "Register scheduled task '$TaskName' (runs as $who)"
if ($apply) {
  if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Write-Host "    Replacing existing task '$TaskName'"
    Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
  }
  Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $taskTrigger -Principal $principal -Settings $settings `
    -Description 'OpenDialer call-center server (installed by scripts\windows\install-service.ps1)' | Out-Null
} else {
  Write-Plan "would register task '$TaskName': cmd.exe /c `"$launcher`" (restart every 1 min on failure, no time limit)"
}

# ---------- firewall ----------
if ($OpenFirewall) {
  $ports = @($Port, $HttpsPort) | Where-Object { $_ -gt 0 }
  Write-Step "Open Windows Firewall for TCP $($ports -join ', ')"
  if ($apply) {
    Get-NetFirewallRule -DisplayName 'OpenDialer' -ErrorAction SilentlyContinue | Remove-NetFirewallRule
    New-NetFirewallRule -DisplayName 'OpenDialer' -Direction Inbound -Protocol TCP -LocalPort $ports -Action Allow -Profile Private, Domain | Out-Null
  } else {
    Write-Plan "would run: New-NetFirewallRule -DisplayName 'OpenDialer' -Direction Inbound -Protocol TCP -LocalPort $($ports -join ',') -Action Allow -Profile Private,Domain"
  }
}

# ---------- start ----------
if (-not $NoStart) {
  Write-Step 'Start the task now'
  if ($apply) { Start-ScheduledTask -TaskName $TaskName } else { Write-Plan "would run: Start-ScheduledTask -TaskName $TaskName" }
}

Write-Host ''
if ($apply) {
  Write-Host "Done. OpenDialer should be reachable at http://localhost:$Port (https://localhost:$HttpsPort) in a few seconds." -ForegroundColor Green
  Write-Host "Logs: $logDir\server.log   Status: Get-ScheduledTask -TaskName $TaskName | Get-ScheduledTaskInfo"
} else {
  Write-Host 'Dry run finished - nothing was changed.' -ForegroundColor Green
}
